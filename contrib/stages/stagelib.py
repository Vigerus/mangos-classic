"""Shared code of the dungeon stage tools (InstanceSubsystem stages, stages/*.xml).

A stages file:

    <root map="289" name="Scholomance">
      <stages>
        <stage name="Reliquary" box="cx cy cz ex ey ez" clearposition="x y z" unclearedposition="x y z"
               canbeenteredincombatifnotcleared="false"/>
        ...                       (stages with the same name are one stage made of several boxes)
      </stages>
      <readonly>                  (generated by update_stagesstaticdata.py, not read by the server)
        <floors>
          <floor id="0" kind="floor|ramp" z="..." area="..."> <poly v="x y z x y z ..."/> ... </floor>
          <link a="0" b="1" x="" y="" z=""/>
        </floors>
        <mobs> <mob name="" entry="" guid="" x="" y="" z=""/> ... </mobs>
      </readonly>
    </root>

box: center and half extents (no rotation). The first stage is the entrance (always cleared on the server).
clearposition / unclearedposition (optional, empty for none): where bots stand while the master is in the stage once
it is cleared / before.
"""

import glob
import math
import os
import re
import struct
import xml.etree.ElementTree as ET
from collections import defaultdict, deque

DEFAULT_CONF = r"F:\server\vanillanew\mangosd.conf"

# ---------------------------------------------------------------- config / database


def read_conf(path):
    """key -> value of a mangosd.conf style file."""
    values = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            match = re.match(r'^\s*([A-Za-z0-9_.]+)\s*=\s*"?([^"\n]*)"?', line)
            if match:
                values[match.group(1)] = match.group(2).strip()
    return values


class ServerData:
    """The server's world database, dbc and mmaps folders (paths from mangosd.conf)."""

    def __init__(self, conf_path=DEFAULT_CONF):
        import mysql.connector

        self.conf_path = conf_path
        conf = read_conf(conf_path)
        server_dir = os.path.dirname(os.path.abspath(conf_path))
        data_dir = conf.get("DataDir", ".")
        if not os.path.isabs(data_dir):
            data_dir = os.path.join(server_dir, data_dir)
        self.dbc_dir = os.path.join(data_dir, "dbc")
        self.mmaps_dir = os.path.join(data_dir, "mmaps")

        host, port, user, password, database = conf["WorldDatabaseInfo"].split(";")
        self.db = mysql.connector.connect(host=host, port=int(port), user=user, password=password, database=database)
        self._factions = None

    def query(self, sql, args=()):
        cursor = self.db.cursor()
        cursor.execute(sql, args)
        rows = cursor.fetchall()
        cursor.close()
        return rows

    # -- dbc

    def faction_friendly_to_players(self, faction_template):
        if self._factions is None:
            self._factions = {}
            for record in read_dbc(os.path.join(self.dbc_dir, "FactionTemplate.dbc")):
                # ID, faction, flags, factionGroupMask, friendGroupMask, enemyGroupMask, ...
                self._factions[record[0]] = record[4]
        return bool(self._factions.get(faction_template, 0) & 1)

    # -- world database

    def instances(self):
        """(map id, max players) of the dungeons and raids."""
        return [(row[0], row[1]) for row in self.query("SELECT map, maxPlayers FROM instance_template WHERE levelMin > 0 ORDER BY map")]

    def entrances(self, map_id):
        """Where players enter the map (areatrigger teleport targets: several for dungeons with wings)."""
        rows = self.query("SELECT target_position_x, target_position_y, target_position_z FROM areatrigger_teleport WHERE target_map = %s ORDER BY id", (map_id,))
        entrances = []
        for row in rows:
            point = tuple(float(v) for v in row)
            if all(math.dist(point, other) > 5 for other in entrances):
                entrances.append(point)
        return entrances

    def entrance(self, map_id):
        """The first entrance, None without one."""
        entrances = self.entrances(map_id)
        return entrances[0] if entrances else None

    def bosses(self, map_id):
        """entry -> encounter name of the creatures killed for the map's encounters."""
        rows = self.query(
            "SELECT e.creditEntry, d.EncounterName FROM instance_encounters e JOIN instance_dungeon_encounters d ON d.Id = e.entry "
            "WHERE d.MapId = %s AND e.creditType = 0", (map_id,))
        return {row[0]: row[1] for row in rows}

    def mobs(self, map_id):
        """Every creature spawn of the map: dicts guid, entry, name, x, y, z, counted (what the server counts in a stage:
        no critters, uninteractible / invisible creatures (triggers), creatures friendly to players)."""
        rows = self.query(
            "SELECT c.guid, c.id, t.Name, c.position_x, c.position_y, c.position_z, t.CreatureType, t.Faction, t.UnitFlags, t.ExtraFlags "
            "FROM creature c JOIN creature_template t ON t.entry = c.id WHERE c.map = %s ORDER BY c.guid", (map_id,))
        mobs = []
        for guid, entry, name, x, y, z, creature_type, faction, unit_flags, extra_flags in rows:
            counted = (creature_type != 8 and not (unit_flags & 0x02000000) and not (extra_flags & 0x80)
                       and not self.faction_friendly_to_players(faction))
            mobs.append({"guid": guid, "entry": entry, "name": name, "x": float(x), "y": float(y), "z": float(z), "counted": counted})
        return mobs


def read_dbc(path):
    """Records of a WDBC file as tuples of uint32 fields."""
    with open(path, "rb") as f:
        data = f.read()
    magic, count, fields, size, _ = struct.unpack_from("<4s4I", data, 0)
    assert magic == b"WDBC", path
    records = []
    for i in range(count):
        records.append(struct.unpack_from("<%dI" % fields, data, 20 + i * size))
    return records


# ---------------------------------------------------------------- navmesh


DT_EXT_LINK = 0x8000


class NavMesh:
    """Walkable polygons of a map's mmaps tiles, in world coordinates (recast stores (y, z, x))."""

    def __init__(self, mmaps_dir, map_id):
        self.polys = []     # list of [(x, y, z), ...]
        self.tile = []      # tile index of each poly
        internal = []       # (poly, neighbour) pairs inside tiles
        external = []       # (poly, edge a, edge b) on tile borders

        for tile_index, path in enumerate(sorted(glob.glob(os.path.join(mmaps_dir, "%03d????.mmtile" % map_id)))):
            with open(path, "rb") as f:
                data = f.read()
            header = struct.unpack_from("<15i", data, 20)
            poly_count, vert_count = header[6], header[7]
            offset = 20 + 100
            raw = struct.unpack_from("<%df" % (vert_count * 3), data, offset)
            verts = [(raw[i * 3 + 2], raw[i * 3], raw[i * 3 + 1]) for i in range(vert_count)]
            offset += vert_count * 12
            base = len(self.polys)
            for p in range(poly_count):
                fields = struct.unpack_from("<I6H6HHBB", data, offset + p * 32)
                poly_verts, neis, count, area_type = fields[1:7], fields[7:13], fields[14], fields[15]
                if area_type >> 6:      # off-mesh connection
                    self.polys.append([])
                    self.tile.append(tile_index)
                    continue
                points = [verts[v] for v in poly_verts[:count]]
                self.polys.append(points)
                self.tile.append(tile_index)
                for e in range(count):
                    nei = neis[e]
                    if not nei:
                        continue
                    if nei & DT_EXT_LINK:
                        external.append((base + p, points[e], points[(e + 1) % count]))
                    else:
                        internal.append((base + p, base + nei - 1))

        self.neighbours = [set() for _ in self.polys]
        for a, b in internal:
            self.neighbours[a].add(b)
            self.neighbours[b].add(a)
        self._link_tiles(external)

    def _link_tiles(self, external):
        """Border edges of neighbouring tiles: same border line, overlapping, about the same height."""
        buckets = defaultdict(list)
        for poly, a, b in external:
            if abs(a[0] - b[0]) < 0.01:
                key, lo, hi = ("x", round(a[0], 1)), min(a[1], b[1]), max(a[1], b[1])
            elif abs(a[1] - b[1]) < 0.01:
                key, lo, hi = ("y", round(a[1], 1)), min(a[0], b[0]), max(a[0], b[0])
            else:
                continue
            buckets[key].append((poly, lo, hi, (a[2] + b[2]) / 2))
        for edges in buckets.values():
            for i in range(len(edges)):
                pa, lo_a, hi_a, za = edges[i]
                for j in range(i + 1, len(edges)):
                    pb, lo_b, hi_b, zb = edges[j]
                    if self.tile[pa] == self.tile[pb]:
                        continue
                    if min(hi_a, hi_b) - max(lo_a, lo_b) > 0.05 and abs(za - zb) < 2.5:
                        self.neighbours[pa].add(pb)
                        self.neighbours[pb].add(pa)

    @staticmethod
    def center(points):
        n = len(points)
        return (sum(p[0] for p in points) / n, sum(p[1] for p in points) / n, sum(p[2] for p in points) / n)

    def area(self, poly):
        points = self.polys[poly]
        s = 0.0
        for i in range(len(points)):
            x1, y1, _ = points[i]
            x2, y2, _ = points[(i + 1) % len(points)]
            s += x1 * y2 - x2 * y1
        return abs(s) / 2

    def find_poly(self, x, y, z, polys=None):
        """The poly under / nearest to the point: containing it in 2D with the closest height, else the nearest center."""
        best, best_dz = None, None
        candidates = polys if polys is not None else range(len(self.polys))
        for poly in candidates:
            points = self.polys[poly]
            if not points or not point_in_polygon(x, y, points):
                continue
            dz = abs(sum(p[2] for p in points) / len(points) - z)
            if best_dz is None or dz < best_dz:
                best, best_dz = poly, dz
        if best is not None and best_dz < 8:
            return best
        nearest, nearest_d = None, None
        for poly in candidates:
            points = self.polys[poly]
            if not points:
                continue
            cx, cy, cz = self.center(points)
            d = (cx - x) ** 2 + (cy - y) ** 2 + ((cz - z) * 2) ** 2
            if nearest_d is None or d < nearest_d:
                nearest, nearest_d = poly, d
        return nearest

    def reachable(self, start):
        """Polys connected to the start poly, with their walking distance from it (between poly centers)."""
        dist = {start: 0.0}
        queue = deque([start])
        centers = {}
        while queue:
            poly = queue.popleft()
            c = centers.setdefault(poly, self.center(self.polys[poly]))
            for nei in self.neighbours[poly]:
                if not self.polys[nei]:
                    continue
                n = centers.setdefault(nei, self.center(self.polys[nei]))
                d = dist[poly] + math.dist(c, n)
                if nei not in dist or d < dist[nei] - 0.01:
                    dist[nei] = d
                    queue.append(nei)
        return dist


def point_in_polygon(x, y, points):
    inside = False
    j = len(points) - 1
    for i in range(len(points)):
        xi, yi = points[i][0], points[i][1]
        xj, yj = points[j][0], points[j][1]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def build_floors(mesh, polys):
    """Groups the reachable polys into floors (flat, connected, about the same height) and ramps (slopes, stairs)
    between them; returns (groups, links): groups are dicts id, kind, polys, z, area; links (a, b, (x, y, z))."""
    polys = set(polys)
    flat = {}
    mean_z = {}
    for poly in polys:
        zs = [p[2] for p in mesh.polys[poly]]
        flat[poly] = max(zs) - min(zs) <= 1.2
        mean_z[poly] = sum(zs) / len(zs)

    group_of = {}
    groups = []
    for start in sorted(polys):
        if start in group_of:
            continue
        gid = len(groups)
        members = []
        queue = deque([start])
        group_of[start] = gid
        while queue:
            poly = queue.popleft()
            members.append(poly)
            for nei in mesh.neighbours[poly]:
                if nei not in polys or nei in group_of or flat[nei] != flat[start]:
                    continue
                if flat[start] and abs(mean_z[nei] - mean_z[poly]) > 1.0:
                    continue
                group_of[nei] = gid
                queue.append(nei)
        groups.append(members)

    # tiny groups (navmesh noise) go to the neighbour group they share the most edges with
    area = [sum(mesh.area(p) for p in members) for members in groups]
    changed = True
    while changed:
        changed = False
        for gid, members in enumerate(groups):
            if not members or area[gid] >= 25.0:
                continue
            shared = defaultdict(int)
            for poly in members:
                for nei in mesh.neighbours[poly]:
                    other = group_of.get(nei)
                    if other is not None and other != gid and groups[other]:
                        shared[other] += 1
            if not shared:
                continue
            target = max(shared, key=lambda g: (shared[g], area[g]))
            for poly in members:
                group_of[poly] = target
            groups[target].extend(members)
            area[target] += area[gid]
            groups[gid] = []
            area[gid] = 0.0
            changed = True

    result = []
    remap = {}
    for gid, members in enumerate(groups):
        if not members:
            continue
        remap[gid] = len(result)
        flat_area = sum(mesh.area(p) for p in members if flat[p])
        z = sum(mean_z[p] * mesh.area(p) for p in members) / max(0.001, area[gid])
        result.append({"id": len(result), "kind": "floor" if flat_area >= area[gid] / 2 else "ramp",
                       "polys": sorted(members), "z": z, "area": area[gid]})

    links = {}
    for poly in polys:
        a = remap[group_of[poly]]
        for nei in mesh.neighbours[poly]:
            if nei not in polys:
                continue
            b = remap[group_of[nei]]
            if a < b and (a, b) not in links:
                c1, c2 = mesh.center(mesh.polys[poly]), mesh.center(mesh.polys[nei])
                links[(a, b)] = tuple((c1[i] + c2[i]) / 2 for i in range(3))
    return result, [(a, b, p) for (a, b), p in sorted(links.items())]


# ---------------------------------------------------------------- xml


def fmt(value):
    return ("%.1f" % value).rstrip("0").rstrip(".") if abs(value - round(value)) > 1e-6 else str(int(round(value)))


def readonly_element(server, map_id, mesh_cache=None):
    """The <readonly> element of a map: navmesh floors reachable from the entrance, and every creature spawn."""
    readonly = ET.Element("readonly")
    floors = ET.SubElement(readonly, "floors")
    entrances = server.entrances(map_id)
    mesh = NavMesh(server.mmaps_dir, map_id)
    reach = {}
    for entrance in entrances if mesh.polys else []:
        start = mesh.find_poly(*entrance)
        if start is None or start in reach:
            continue
        for poly, d in mesh.reachable(start).items():
            if poly not in reach or d < reach[poly]:
                reach[poly] = d
    if reach:
        groups, links = build_floors(mesh, reach.keys())
        for group in groups:
            floor = ET.SubElement(floors, "floor", id=str(group["id"]), kind=group["kind"], z=fmt(group["z"]), area=fmt(group["area"]))
            for poly in group["polys"]:
                ET.SubElement(floor, "poly", v=" ".join(fmt(c) for p in mesh.polys[poly] for c in p))
        for a, b, (x, y, z) in links:
            ET.SubElement(floors, "link", a=str(a), b=str(b), x=fmt(x), y=fmt(y), z=fmt(z))
    if entrances:
        floors.set("entrance", "; ".join(" ".join(fmt(c) for c in entrance) for entrance in entrances))

    mobs = ET.SubElement(readonly, "mobs")
    for mob in server.mobs(map_id):
        ET.SubElement(mobs, "mob", name=mob["name"], entry=str(mob["entry"]), guid=str(mob["guid"]),
                      x=fmt(mob["x"]), y=fmt(mob["y"]), z=fmt(mob["z"]))
    if mesh_cache is not None:
        mesh_cache[map_id] = (mesh, reach)
    return readonly


def indent(element, level=0):
    pad = "\n" + "  " * level
    if len(element):
        if not element.text or not element.text.strip():
            element.text = pad + "  "
        for child in element:
            indent(child, level + 1)
        if not child.tail or not child.tail.strip():
            child.tail = pad
    if level and (not element.tail or not element.tail.strip()):
        element.tail = pad


def write_xml(root, path):
    indent(root)
    tree = ET.ElementTree(root)
    with open(path, "wb") as f:
        f.write(b'<?xml version="1.0" encoding="utf-8"?>\n')
        tree.write(f, encoding="utf-8")
        f.write(b"\n")


def parse_box(text):
    values = [float(v) for v in text.split()]
    if len(values) != 6:
        raise ValueError("box needs 'cx cy cz ex ey ez', got '%s'" % text)
    return values


def parse_point(text):
    if not text or not text.strip():
        return None
    values = [float(v) for v in text.split()]
    if len(values) != 3:
        raise ValueError("position needs 'x y z', got '%s'" % text)
    return values


def stages_files(directory):
    return sorted(glob.glob(os.path.join(directory, "*.xml")))
